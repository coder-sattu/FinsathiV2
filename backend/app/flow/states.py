"""State definitions for the chat state machine."""

from enum import Enum


class State(str, Enum):
    """Conversation states."""

    CONSENT = "CONSENT"
    LANGUAGE_CHOICE = "LANGUAGE_CHOICE"
    AUTH_CHOICE = "AUTH_CHOICE"
    POLICY_INPUT = "POLICY_INPUT"
    MEMBER_VERIFY = "MEMBER_VERIFY"
    RMN_INPUT = "RMN_INPUT"
    OTP_INPUT = "OTP_INPUT"
    SELECT_POLICY = "SELECT_POLICY"
    POLICY_CHECK = "POLICY_CHECK"
    DUP_CHECK = "DUP_CHECK"
    OPEN_CLAIM = "OPEN_CLAIM"
    DOA_CHECK = "DOA_CHECK"
    CLAIM_TYPE = "CLAIM_TYPE"
    SELF_I_OFFER = "SELF_I_OFFER"
    PATIENT = "PATIENT"
    PATIENT_CONFIRM = "PATIENT_CONFIRM"
    ADMISSION = "ADMISSION"
    ADMISSION_CONFIRM = "ADMISSION_CONFIRM"
    HOSPITAL_PIN = "HOSPITAL_PIN"
    HOSPITAL_PICK = "HOSPITAL_PICK"
    NON_NETWORK = "NON_NETWORK"
    HOSPITAL_CONFIRM = "HOSPITAL_CONFIRM"
    REVIEW = "REVIEW"
    SUBMIT = "SUBMIT"
    DOC_CHOICE = "DOC_CHOICE"
    DOC_UPLOAD = "DOC_UPLOAD"

    # terminal states
    END_NO_CONSENT = "END_NO_CONSENT"
    DONE = "DONE"
    SR_PENDING = "SR_PENDING"
    AGENT_HANDOFF = "AGENT_HANDOFF"
    LOCKED = "LOCKED"
    END_INACTIVE = "END_INACTIVE"
    END_TRACK = "END_TRACK"
    END_REDIRECT = "END_REDIRECT"


TERMINAL_STATES = {
    State.END_NO_CONSENT,
    State.DONE,
    State.SR_PENDING,
    State.AGENT_HANDOFF,
    State.LOCKED,
    State.END_INACTIVE,
    State.END_TRACK,
    State.END_REDIRECT,
}
